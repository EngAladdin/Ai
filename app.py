@app.route('/predict', methods=['POST'])
def predict():
    data = request.get_json(silent=True)
    if not data:
        return jsonify({'error': 'طلب غير صالح'}), 400
    symptoms = data.get('symptoms', [])
    if not symptoms:
        return jsonify({'error': 'لم يتم اختيار أي أعراض'}), 400
    if not isinstance(symptoms, list):
        return jsonify({'error': 'صيغة الأعراض غير صحيحة'}), 400
    if len(symptoms) < 2:
        return jsonify({'error': 'يرجى اختيار عرضين على الأقل للحصول على نتائج دقيقة'}), 400
    if len(symptoms) > 50:
        return jsonify({'error': 'عدد الأعراض كبير جداً (الحد الأقصى 50)'}), 400
    invalid = [s for s in symptoms if not isinstance(s, str) or s not in VALID_SYMPTOMS]
    if invalid:
        return jsonify({'error': f'أعراض غير معروفة: {", ".join(str(i) for i in invalid[:5])}'}), 400
    symptoms = list(dict.fromkeys(symptoms))
    try:
        results = predict_with_model(symptoms) if MODEL else predict_fallback(symptoms)
    except Exception as e:
        logger.error(f"Prediction error: {e}")
        return jsonify({'error': 'حدث خطأ أثناء التحليل، يرجى المحاولة مرة أخرى'}), 500
    return jsonify({'results': results, 'model_used': MODEL is not None})


